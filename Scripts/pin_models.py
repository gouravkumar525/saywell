#!/usr/bin/env python3
"""Writes Sources/LocalFlowCore/ModelManifests.swift (B3) from Hugging Face cache
snapshots: repo, revision (the snapshot's commit), and each file's size + SHA-256.

Usage: python3 Scripts/pin_models.py mlx-community/Qwen3-4B-Instruct-2507-4bit [...]
       ... org/repo@<commit>=<local folder>   (a verified copy outside the HF cache, e.g. Parakeet)
Run it after downloading a new revision with mlx-lm or the app, then rebuild."""
import hashlib, os, sys

SKIP = {"README.md", ".gitattributes"}
hub = os.environ.get("HF_HUB_CACHE") or os.path.join(
    os.environ.get("HF_HOME", os.path.expanduser("~/.cache/huggingface")), "hub")

def manifest(spec):
    if "=" in spec:
        repo_rev, snap = spec.split("=", 1)
        repo, rev = repo_rev.split("@")
    else:
        repo = spec
        base = os.path.join(hub, "models--" + repo.replace("/", "--"))
        rev = open(os.path.join(base, "refs", "main")).read().strip()
        snap = os.path.join(base, "snapshots", rev)
    names = []
    for root, _, fs in os.walk(snap):
        names += [os.path.relpath(os.path.join(root, f), snap) for f in fs]
    files = []
    for name in sorted(names):
        if os.path.basename(name) in SKIP or name.startswith(".") or os.path.basename(name) == ".DS_Store":
            continue
        path = os.path.realpath(os.path.join(snap, name))
        h = hashlib.sha256()
        with open(path, "rb") as f:
            for block in iter(lambda: f.read(1 << 20), b""):
                h.update(block)
        files.append((name, os.path.getsize(path), h.hexdigest()))
    return repo, rev, files

out = ["// Generated by Scripts/pin_models.py; do not edit by hand.",
       "", "public extension ModelManifest {", "    static let pinned: [ModelManifest] = ["]
for spec in sys.argv[1:]:
    repo, rev, files = manifest(spec)
    out.append(f'        ModelManifest(repo: "{repo}", revision: "{rev}", files: [')
    for name, size, sha in files:
        out.append(f'            .init(name: "{name}", size: {size}, sha256: "{sha}"),')
    out.append("        ]),")
out += ["    ]", "}", ""]
dest = os.path.join(os.path.dirname(__file__), "..", "Sources", "LocalFlowCore", "ModelManifests.swift")
open(dest, "w").write("\n".join(out))
print("wrote", os.path.normpath(dest))
